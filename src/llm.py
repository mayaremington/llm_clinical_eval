"""Minimal provider-agnostic chat wrapper with retries.

Providers:
  anthropic          needs ANTHROPIC_API_KEY  (pip install anthropic)
  openai             needs OPENAI_API_KEY     (pip install openai)
  openai_compatible  any OpenAI-style server via base_url (Ollama, vLLM, LM Studio...)
  mock               no key; deterministic fake outputs for dry runs
"""
from __future__ import annotations

import hashlib
import json
import os
import random
import re
import time


def complete(provider: str, model: str, prompt: str, *, temperature: float = 0.0,
             max_tokens: int = 2000, base_url: str | None = None, retries: int = 4) -> dict:
    """Return {"text": str, "input_tokens": int|None, "output_tokens": int|None, "latency_s": float}."""
    last_err = None
    for attempt in range(retries):
        t0 = time.time()
        try:
            text, tin, tout = _call(provider, model, prompt, temperature, max_tokens, base_url)
            return {"text": text, "input_tokens": tin, "output_tokens": tout,
                    "latency_s": round(time.time() - t0, 2)}
        except Exception as e:  # noqa: BLE001 - retry on any transient API error
            last_err = e
            wait = 2 ** attempt + random.random()
            print(f"  [{provider}:{model}] error: {e!r}; retrying in {wait:.1f}s")
            time.sleep(wait)
    raise RuntimeError(f"{provider}:{model} failed after {retries} attempts: {last_err!r}")


def _call(provider, model, prompt, temperature, max_tokens, base_url):
    if provider == "anthropic":
        import anthropic
        client = anthropic.Anthropic()
        r = client.messages.create(model=model, max_tokens=max_tokens, temperature=temperature,
                                   messages=[{"role": "user", "content": prompt}])
        text = "".join(b.text for b in r.content if getattr(b, "type", "") == "text")
        return text, r.usage.input_tokens, r.usage.output_tokens

    if provider in ("openai", "openai_compatible"):
        from openai import OpenAI
        kwargs = {}
        if base_url:
            kwargs["base_url"] = base_url
            kwargs["api_key"] = os.environ.get("OPENAI_API_KEY", "not-needed-for-local")
        client = OpenAI(**kwargs)
        r = client.chat.completions.create(model=model, temperature=temperature, max_tokens=max_tokens,
                                           messages=[{"role": "user", "content": prompt}])
        u = r.usage
        return r.choices[0].message.content, getattr(u, "prompt_tokens", None), getattr(u, "completion_tokens", None)

    if provider == "mock":
        return _mock(model, prompt), None, None

    raise ValueError(f"Unknown provider: {provider}")


# ---------------------------------------------------------------------------
# Mock provider: lets you run the whole pipeline without any API key.
# ---------------------------------------------------------------------------
_CODES = ["HALLUCINATION", "OMISSION", "NEGATION", "NUMERIC_MED", "MISATTRIBUTION",
          "LATERALITY_LOCATION", "TEMPORAL", "SECTION"]


def _mock(model: str, prompt: str) -> str:
    rng = random.Random(int(hashlib.md5((model + prompt).encode()).hexdigest()[:8], 16))
    if "Return ONLY valid JSON" in prompt:  # judge call
        errors = []
        for _ in range(rng.choice([0, 0, 1, 1, 2, 3])):
            errors.append({"category": rng.choice(_CODES), "severity": rng.choice([1, 1, 2, 2, 3]),
                           "note_text": "mock", "transcript_evidence": "mock", "explanation": "mock error"})
        return json.dumps({"errors": errors})
    transcript = prompt.split("TRANSCRIPT:", 1)[-1]
    lines = [re.sub(r"^\[\w+\]\s*", "", ln).strip() for ln in transcript.strip().splitlines()]
    patient = [ln for ln in lines if ln][:6]
    return ("CHIEF COMPLAINT\n" + (patient[0][:80] if patient else "") +
            "\n\nHISTORY OF PRESENT ILLNESS\n" + " ".join(patient[1:5]) +
            "\n\nASSESSMENT AND PLAN\nMock plan generated by " + model + ".")
